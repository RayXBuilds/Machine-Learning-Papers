#!/usr/bin/env python3
"""Generate topic/year catalogs and reading paths from guide metadata; --check detects drift."""
import argparse
import collections
import json
import re
from urllib.parse import quote
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SECTIONS = ('解决的问题', '主要方法', '贡献与局限', '前置知识与阅读重点', '收录理由', '相关主题与版本')

def load_articles():
    topics = json.loads((ROOT / 'docs/catalog-topics.json').read_text())
    rows = []
    ids = set()
    for p in sorted((ROOT / 'papers').glob('*/*.md')):
        if p.name == 'README.md':
            continue
        text = p.read_text()
        front = text.split('---', 2)[1]
        meta = dict(re.findall(r'^(\w+): (.+)$', front, re.M))
        for k in ('id', 'primary_topic', 'tags', 'source', 'status', 'catalog_year', 'subtopic'):
            if k not in meta:
                raise ValueError(f'{p}: missing {k}')
        topic = meta['primary_topic']
        group = json.loads(meta['subtopic'])
        if topic != p.parent.name or group not in topics[topic]['groups']:
            raise ValueError(f'{p}: invalid topic/subtopic')
        if meta['id'] in ids:
            raise ValueError(f'{p}: duplicate id')
        ids.add(meta['id'])
        year = meta['catalog_year']
        if not re.fullmatch(r'(?:\d{4}|undated)', year) or not p.name.startswith(year + '-'):
            raise ValueError(f'{p}: invalid catalog year')
        for section in SECTIONS:
            if '\n## ' + section + '\n' not in text:
                raise ValueError(f'{p}: missing section {section}')
        problem = text.split('## 解决的问题\n', 1)[1].split('\n## ', 1)[0].strip()
        problem = re.sub(r'\[([^\]]+)\]\([^)]+\)', r'\1', problem).replace('\n', ' ')
        problem = problem if len(problem) <= 90 else problem[:87] + '…'
        rows.append(dict(id=meta['id'], topic=topic, group=group, year=year,
                         title=re.search(r'^# (.+)$', text, re.M)[1], problem=problem,
                         path=p.relative_to(ROOT).as_posix()))
    return topics, rows

def safe(text):
    return text.replace('|', '\\|')

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    topics, rows = load_articles()
    pdfs = json.loads((ROOT / 'docs/pdfs.json').read_text())
    outputs = {}
    new = {r['path'] for r in pdfs.values() if r.get('path', '').startswith('pdfs/')}
    reused = sum(r.get('path', '').startswith('library/') for r in pdfs.values())
    pending = sum('path' not in r for r in pdfs.values())
    marker = '<!-- Generated by scripts/build_catalog.py; edit guide metadata or catalog config. -->\n\n'
    for topic, cfg in topics.items():
        items = [a for a in rows if a['topic'] == topic]
        out = f"# {cfg['name']}\n\n" + marker
        out += '[全部主题](../README.md) · [年份导航](../../docs/years/README.md) · [学习路线](../../docs/reading-paths.md) · [首页](../../README.md)\n\n'
        out += f"范围：{cfg['scope']}。本主题 {len(items)} 篇独立导读；按子方向分组，组内按归档年份升序排列。\n\n"
        for group in cfg['groups']:
            members = sorted((a for a in items if a['group'] == group), key=lambda a: (a['year'], a['title'].lower()))
            if not members:
                continue
            out += f'## {group}\n\n| 归档年 | 论文与导读 | PDF | 阅读问题 |\n| --- | --- | --- | --- |\n'
            for a in members:
                record = pdfs[a['path']]
                pdf = f"[PDF](../../{quote(record['path'])})" if record.get('path') else record['reason']
                out += f"| {a['year']} | [{safe(a['title'])}]({Path(a['path']).name}) | {pdf} | {safe(a['problem'])} |\n"
            out += '\n'
        out += '## 跨主题阅读\n\n通过[学习路线](../../docs/reading-paths.md)查找相关方法；跨主题只链接主文件，不复制文章或重复计数。\n\n## 历史 PDF\n\n'
        n = cfg['archive_count']
        out += f'[浏览本主题历史资料（{n} 份）](../../library/{topic}/README.md)。\n' if n else '本主题尚无历史 PDF。\n'
        outputs[f'papers/{topic}/README.md'] = out
    total = len(rows)
    out = '# 按主题查找论文与文章\n\n' + marker
    out += '[首页](../README.md) · [年份导航](../docs/years/README.md) · [学习路线](../docs/reading-paths.md) · [每日收录](../docs/daily/README.md)\n\n'
    out += '| 主题 | 内容范围 | 导读 | 历史 PDF |\n| --- | --- | ---: | ---: |\n'
    for topic,cfg in topics.items():
        n = sum(a['topic'] == topic for a in rows)
        out += f"| [{cfg['name']}]({topic}/README.md) | {cfg['scope']} | {n} | {cfg['archive_count']} |\n"
    out += f'\n共 {total} 篇独立导读、{sum(c["archive_count"] for c in topics.values())} 份历史 PDF。交叉主题链接不重复计数。\n'
    outputs['papers/README.md'] = out
    out = '# 按归档年份查找\n\n' + marker
    out += '[首页](../../README.md) · [主题目录](../../papers/README.md) · [学习路线](../reading-paths.md)\n\n'
    out += f'全库 {total} 篇独立导读。归档年沿用各条目明确说明的会议、出版或预印本口径，并非统一的首次发表年份；具体版本差异请查看导读的“年份与版本”。收录日期和核实日期不用于论文年份排序。\n\n'
    years = sorted(set(a['year'] for a in rows))
    out += ' · '.join(f'[{y}（{sum(a["year"]==y for a in rows)}）](#year-{y})' for y in years) + '\n\n'
    for y in years:
        out += f'<a id="year-{y}"></a>\n\n## {y}\n\n| 主主题 | 论文与导读 |\n| --- | --- |\n'
        for a in sorted((a for a in rows if a['year']==y),key=lambda a:(a['topic'],a['title'].lower())):
            out += f"| {topics[a['topic']]['name']} | [{safe(a['title'])}](../../{a['path']}) |\n"
        out += '\n'
    outputs['docs/years/README.md'] = out
    routes = json.loads((ROOT/'docs/reading-paths.json').read_text())
    byid = {a['id']: a for a in rows}
    out = '# 按学习目标阅读\n\n' + marker
    out += '[首页](../README.md) · [主题目录](../papers/README.md) · [年份导航](years/README.md) · [最初 26 篇经典索引](classics.md)\n\n'
    out += '以下是按前置知识和比较问题组织的选读路线，不要求读完全部文章，也不表示每两篇之间存在直接技术继承。年份以条目说明为准。当前导读均为概要，不代表全文精读或实验复现。\n\n'
    for route in routes:
        out += f"## {route['name']}\n\n{route['goal']}\n\n"
        for i,id in enumerate(route['ids'],1):
            a=byid[id]
            out += f"{i}. [{a['title']}](../{a['path']})（{a['year']}，{topics[a['topic']]['name']}）\n"
        out += '\n'
    outputs['docs/reading-paths.md'] = out
    out = '# 导读与 PDF 对照\n\n' + marker
    out += f'{total} 篇导读，新增文件区收录 {len(new)} 份 PDF，{reused} 篇复用历史文件，{pending} 篇待补或仅有网页。[来源、取得日期、字节数与 SHA-256](pdfs.json)\n\n'
    for topic, cfg in topics.items():
        out += f"## {cfg['name']}\n\n| 中文导读 | 仓库内 PDF | 文件版本或待补原因 | 来源 |\n| --- | --- | --- | --- |\n"
        for a in (row for row in rows if row['topic'] == topic):
            r = pdfs[a['path']]
            link = f"[PDF](../{quote(r['path'])})" if r.get('path') else '—'
            out += f"| [{safe(a['title'])}](../{a['path']}) | {link} | {safe(r.get('version') or r['reason'])} | [来源]({r['source_url']}) |\n"
        out += '\n'
    outputs['docs/pdf-index.md'] = out
    # Keep editorial homepage prose; regenerate only table counts and total figures.
    for filename in ('README.md','README.en.md'):
        text=(ROOT/filename).read_text()
        for topic in topics:
            n=sum(a['topic']==topic for a in rows)
            pattern=r'(\| \[[^\n]+\]\(papers/'+re.escape(topic)+r'/README.md\) \| [^\n]+? \| )\d+( \| \d+ \|)'
            c = topics[topic]
            label = c['english_name'] if filename.endswith('.en.md') else c['name']
            scope = c['english_scope'] if filename.endswith('.en.md') else c['scope']
            row = f"| [{label}](papers/{topic}/README.md) | {scope} | {n} | {c['archive_count']} |"
            text,count=re.subn(pattern,lambda m:row,text)
            if count!=1:raise ValueError(f'{filename}: missing/duplicate {topic} row')
        text=re.sub(r'\d+ 篇独立导读、147 份历史 PDF',f'{total} 篇独立导读、147 份历史 PDF',text)
        text=re.sub(r'\d+ independent reading guides and 147 archived PDFs',f'{total} independent reading guides and 147 archived PDFs',text)
        summary = (f'Guide PDFs: {len(new)} files in the new collection, {reused} guides linked to archived files, '
                   f'{pending} entries without a local PDF. [PDF index](docs/pdf-index.md).') if filename.endswith('.en.md') else (
                   f'导读配套 PDF：新增文件区 {len(new)} 份，复用历史文件 {reused} 篇，尚无本地 PDF 的条目 {pending} 篇。[逐篇查看](docs/pdf-index.md)。')
        text,count = re.subn(r'^<!-- pdf-count -->.*$', '<!-- pdf-count -->' + summary, text, flags=re.M)
        if count != 1:
            raise ValueError(f'{filename}: missing PDF summary marker')
        outputs[filename]=text
    stale=[]
    for filename,text in outputs.items():
        text = text.rstrip() + "\n"
        p=ROOT/filename
        if not p.exists() or p.read_text()!=text:
            stale.append(filename)
            if not args.check:
                p.parent.mkdir(parents=True,exist_ok=True)
                p.write_text(text)
    if args.check and stale:
        raise SystemExit('Catalog drift: '+', '.join(stale))
    print(f'PASS: {total} guides, {len(topics)} topics, {len(years)} years; '+('catalogs current' if args.check else f'{len(stale)} files generated'))

if __name__=='__main__':
    main()
